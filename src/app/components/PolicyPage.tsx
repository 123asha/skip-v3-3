const textStyle = BODY_LONG_STYLE;

const h2Style: React.CSSProperties = {
  fontFamily: 'var(--font-display)',
  fontSize: 'var(--h2-size)',
  fontWeight: 'var(--h2-weight)' as React.CSSProperties['fontWeight'],
  lineHeight: 'var(--h2-lh)',
  letterSpacing: 'var(--h2-ls)',
  color: 'var(--c-text)',
};

export default function PolicyPage() {
  const pageRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const mainLenis = (window as any).__lenis;
    if (mainLenis) mainLenis.stop();
    const prev = document.documentElement.style.overflowY;
    document.documentElement.style.overflowY = 'hidden';

    const el = pageRef.current!;
    const stopBubble = (e: WheelEvent) => e.stopPropagation();
    el.addEventListener('wheel', stopBubble, { passive: true });

    return () => {
      el.removeEventListener('wheel', stopBubble);
      if (mainLenis) mainLenis.start();
      document.documentElement.style.overflowY = prev;
    };
  }, []);

  return (
    <div className={s.page} ref={pageRef}>
      <div className={s.body} style={{ paddingLeft: 20, paddingRight: 20, paddingBottom: 200, paddingTop: 'calc(var(--pad) + var(--text-size) * var(--text-lh) + 20px)' }}>
        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(5, 1fr)', gap: 20, alignItems: 'start' }}>
          {/* Heading — cols 1–2, in-flow alongside the text */}
          <h1
            className={s.title}
            style={{
              position: 'static',
              left: 'auto',
              top: 'auto',
              gridColumn: '1 / 3',
            }}
          >
            Политика<br />конфиденциальности
          </h1>
          {/* Text — cols 3–4, 2 columns wide */}
          <div style={{ gridColumn: '3 / 5' }}>
            {paragraphs.map((p, i) => (
              <p
                key={i}
                style={{
                  ...(p.heading ? h2Style : textStyle),
                  marginTop: p.heading ? 40 : 0,
                  marginBottom: 16,
                  whiteSpace: 'pre-wrap',
                }}
              >
                {renderWithLinks(p.text, p.heading ? h2Style : textStyle)}
              </p>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
}
